const catalogues: Record<Locale, Shape<Catalogue>> = { de, en }

export const locale = ref<Locale>('de')

export function setLocale(next: Locale) {
  locale.value = next
  if (typeof document !== 'undefined')
    document.documentElement.lang = next
}

function lookup(cat: unknown, key: string): string | undefined {
  let node: unknown = cat
  for (const part of key.split('.')) {
    if (node && typeof node === 'object' && part in node)
      node = (node as Record<string, unknown>)[part]
    else
      return undefined
  }
  return typeof node === 'string' ? node : undefined
}

/** Translate `key` (dot path) and fill `{name}` placeholders. Reactive through `locale`. */
export function t(key: string, params?: Record<string, string | number>): string {
  const text = lookup(catalogues[locale.value], key) ?? lookup(de, key) ?? key
  if (!params)
    return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match)
}

export function formatDateTime(ms: number): string {
  const date = new Date(ms)
  const now = new Date()
  const time = date.toLocaleTimeString(locale.value, { hour: '2-digit', minute: '2-digit' })
  const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime()
  if (ms >= startOfToday)
    return t('start.today', { time })
  if (ms >= startOfToday - 86_400_000)
    return t('start.yesterday', { time })
  return date.toLocaleDateString(locale.value, { day: 'numeric', month: 'long', year: 'numeric' })
}

export const platform = ref<string>('linux')

/** Shortcut text for tooltips and menus, e.g. keys('Ctrl+Shift+Z') → "Strg+Umschalt+Z" or "⇧⌘Z". */
export function keys(combo: string): string {
  if (platform.value === 'darwin') {
    return combo.replace('Ctrl+', '⌘').replace('Shift+', '⇧').replace('Alt+', '⌥')
  }
  if (locale.value === 'de')
    return combo.replace('Ctrl', 'Strg').replace('Shift', 'Umschalt').replace(/^Del$/, 'Entf')
  return combo
}
